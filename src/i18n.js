export function getLanguage() { return language; }
export function setLanguage(value) {
  language = value === 'he' ? 'he' : 'en';
  try { localStorage.setItem(STORAGE_KEY, language); } catch { /* Storage is optional. */ }
}
export function t(key) { return messages[key]?.[language === 'he' ? 1 : 0] ?? key; }
export function localizedError(key) { return Object.assign(new Error(t(key)), { translationKey: key }); }
